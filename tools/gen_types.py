"""Generate TypedDict modules (src/bunny_cdn_sdk/models/) from the saved Bunny OpenAPI specs.

Stdlib only. Usage:
    python tools/gen_types.py          # write the modules
    python tools/gen_types.py --check  # exit 1 if the modules would change
    python tools/gen_types.py --ops    # print the operation maps (all specs) as JSON

The types are for static checking only; at runtime values stay plain dicts.
"""

from __future__ import annotations

import gzip
import json
import keyword
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPECS = ROOT / "docs" / "apis"
OUT = ROOT / "src" / "bunny_cdn_sdk" / "models"
MODULES = ("core", "shield", "logging", "storage", "partner")
HEADER = (
    "# Generated by tools/gen_types.py - do not edit.\n"
    "# fmt: off\n"
    '"""TypedDicts for the Bunny {mod} API (static checking only; values are plain dicts)."""\n\n'
    "from __future__ import annotations\n\n"
)
# Names a generated class/alias must never take (builtins used in annotations, typing imports).
RESERVED = {"Any", "TypedDict", "OPERATIONS", "dict", "list", "int", "str", "float", "bool", "None"}
# Field names that would shadow a type used in the same class body -> functional TypedDict form.
SHADOWING_KEYS = {"dict", "list", "int", "str", "float", "bool", "Any", "None"}
SIMPLE = {"integer": "int", "number": "float", "string": "str", "boolean": "bool"}
METHODS = ("get", "put", "post", "delete", "patch", "options", "head")
ENUM_COMMENT_MAX = 80


def lit(v: str | None) -> str:
    return "None" if v is None else json.dumps(v)


def pascal(text: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in re.split(r"[^0-9A-Za-z]+", text) if p)


def class_name(text: str) -> str:
    name = pascal(text) or "Model"
    return f"N{name}" if name[0].isdigit() else name


def docstring(desc: str | None) -> str | None:
    if not desc or not desc.strip():
        return None
    line = " ".join(desc.split())
    if len(line) > 100:
        line = line[:97].rstrip() + "..."
    return line.replace("\\", "\\\\").replace('"', '\\"')


def enum_comment(s: dict) -> str:
    vals = s.get("enum")
    if not vals:
        return ""
    names = s.get("x-enumNames")
    if names and len(names) == len(vals):
        text = ", ".join(f"{v}={n}" for v, n in zip(vals, names, strict=True))
    else:
        text = ", ".join(str(v) for v in vals)
    return f"  # {text}" if len(text) <= ENUM_COMMENT_MAX else ""


class Generator:
    def __init__(self, spec: dict) -> None:
        self.spec = spec
        self.schemas: dict = (
            spec.get("components", {}).get("schemas") or spec.get("definitions") or {}
        )
        self.used: set[str] = set(RESERVED)
        self.names: dict[str, str] = {}
        for key in sorted(self.schemas):
            self.names[key] = self.unique(class_name(key))
        self.defs: dict[str, str] = {}  # emitted name -> source text
        self.uses_any = False
        self.uses_typeddict = False

    def unique(self, name: str) -> str:
        cand, i = name, 2
        while cand in self.used:
            cand, i = f"{name}{i}", i + 1
        self.used.add(cand)
        return cand

    def resolve(self, obj: dict) -> dict:
        """Follow a local $ref (any component kind) until a non-ref object."""
        seen = 0
        while isinstance(obj, dict) and "$ref" in obj and seen < 20:
            node = self.spec
            for part in obj["$ref"].lstrip("#/").split("/"):
                node = node.get(part.replace("~1", "/").replace("~0", "~"), {})
            obj, seen = node, seen + 1
        return obj

    def ref_name(self, ref: str) -> str:
        key = ref.rsplit("/", 1)[-1]
        return self.names.get(key) or class_name(key)

    def merged_props(self, s: dict, seen: tuple = ()) -> dict:
        props: dict = {}
        if "$ref" in s and s["$ref"] not in seen:
            props.update(self.merged_props(self.resolve(s), (*seen, s["$ref"])))
        for part in s.get("allOf", []):
            props.update(self.merged_props(part, seen))
        props.update(s.get("properties", {}))
        return props

    def is_object(self, s: dict) -> bool:
        if "properties" in s:
            return True
        parts = s.get("allOf")
        return bool(parts) and (len(parts) > 1 or "$ref" not in parts[0])

    def any_(self) -> str:
        self.uses_any = True
        return "Any"

    def texpr(self, s: dict, ctx: str) -> str:
        """Type expression for schema s; inline objects are emitted as classes named from ctx."""
        if not isinstance(s, dict) or not s:
            return self.any_()
        nullable = bool(s.get("nullable") or s.get("x-nullable"))
        typ = s.get("type")
        if isinstance(typ, list):
            nullable = nullable or "null" in typ
            rest = [t for t in typ if t != "null"]
            typ = rest[0] if len(rest) == 1 else None
        expr = self._base(s, typ, ctx)
        if nullable and expr not in ("None", "Any"):
            expr += " | None"
        return expr

    def _base(self, s: dict, typ: str | None, ctx: str) -> str:  # noqa: PLR0911
        if "$ref" in s:
            return self.ref_name(s["$ref"])
        union = s.get("oneOf") or s.get("anyOf")
        if union:
            parts = [self.texpr(p, f"{ctx}Option{i}") for i, p in enumerate(union, 1)]
            parts = list(dict.fromkeys(parts))
            if "Any" in parts:
                return self.any_()
            return " | ".join(parts)
        if self.is_object(s):
            name = self.unique(ctx)
            self.emit_class(name, s)
            return name
        if "allOf" in s:
            return self.texpr(s["allOf"][0], ctx)
        if typ == "array":
            return f"list[{self.texpr(s.get('items') or {}, f'{ctx}Item')}]"
        if typ in SIMPLE:
            return SIMPLE[typ]
        if typ == "null":
            return "None"
        if "enum" in s and typ is None:
            return "int" if all(isinstance(v, int) for v in s["enum"]) else "str"
        if typ == "object" or "additionalProperties" in s:
            ap = s.get("additionalProperties")
            if isinstance(ap, dict) and ap:
                return f"dict[str, {self.texpr(ap, f'{ctx}Value')}]"
            self.uses_any = True
            return "dict[str, Any]"
        return self.any_()

    def emit_class(self, name: str, s: dict) -> None:
        self.uses_typeddict = True
        fields: list[tuple[str, str, str]] = []
        for key, prop in sorted(self.merged_props(s).items()):
            expr = self.texpr(prop, name + pascal(key))
            fields.append((key, expr, enum_comment(prop) if isinstance(prop, dict) else ""))
        functional = any(
            not k.isidentifier() or keyword.iskeyword(k) or k in SHADOWING_KEYS
            for k, _, _ in fields
        )
        doc = docstring(s.get("description"))
        if functional:
            body = ", ".join(f'"{k}": "{e}"' for k, e, _ in fields)
            self.defs[name] = f'{name} = TypedDict("{name}", {{{body}}}, total=False)\n'
            return
        lines = [f"class {name}(TypedDict, total=False):"]
        if doc:
            lines.append(f'    """{doc}"""')
            if fields:
                lines.append("")
        lines += [f"    {k}: {e}{c}" for k, e, c in fields]
        if not doc and not fields:
            lines.append("    pass")
        self.defs[name] = "\n".join(lines) + "\n"

    def emit_schemas(self) -> None:
        for key in sorted(self.schemas):
            s, name = self.schemas[key], self.names[key]
            if self.is_object(s):
                self.emit_class(name, s)
            else:
                self.defs[name] = f"type {name} = {self.texpr(s, name)}{enum_comment(s)}\n"

    def pick_schema(self, content: dict) -> dict | None:
        # Only content types that carry a schema (storage puts examples under application/json
        # and the schema under */*).
        content = {c: v for c, v in (content or {}).items() if (v or {}).get("schema")}
        if not content:
            return None
        ctype = next((c for c in content if c == "application/json"), None)
        ctype = ctype or next((c for c in sorted(content) if c.endswith("json")), None)
        ctype = ctype or next(iter(content))
        s = content[ctype]["schema"]
        if not s or s.get("format") == "binary":
            return None
        return s

    def type_name(self, s: dict, ctx: str) -> str:
        """Importable name for schema s: a class/alias name, creating an alias when needed."""
        expr = self.texpr(s, ctx)
        if re.fullmatch(r"[A-Za-z_]\w*", expr) and expr not in {*SIMPLE.values(), "Any"}:
            return expr
        name = self.unique(ctx)
        self.defs[name] = f"type {name} = {expr}\n"
        return name

    def operations(self) -> dict[str, tuple[str | None, str | None]]:
        ops: dict[str, tuple[str | None, str | None]] = {}
        for path in sorted(self.spec.get("paths", {})):
            item = self.spec["paths"][path]
            for method in METHODS:
                op = item.get(method)
                if not op:
                    continue
                base = class_name(op.get("operationId") or f"{method} {path}")
                body = self.pick_schema(
                    self.resolve(op.get("requestBody") or {}).get("content", {})
                )
                req = self.type_name(body, f"{base}Request") if body else None
                resp = None
                responses = op.get("responses", {})
                for code in sorted(c for c in responses if str(c).startswith("2")):
                    schema = self.pick_schema(self.resolve(responses[code]).get("content", {}))
                    if schema:
                        resp = self.type_name(schema, f"{base}Response")
                        break
                ops[f"{method.upper()} {path}"] = (req, resp)
        return ops

    def render(self, mod: str) -> tuple[str, dict]:
        self.emit_schemas()
        ops = self.operations()
        imports = [
            n for n, used in (("Any", self.uses_any), ("TypedDict", self.uses_typeddict)) if used
        ]
        out = HEADER.format(mod=mod)
        if imports:
            out += f"from typing import {', '.join(imports)}\n\n\n"
        out += "\n".join(self.defs[k] + "\n" for k in sorted(self.defs))
        out += "\nOPERATIONS: dict[str, tuple[str | None, str | None]] = {\n"
        for key, (req, resp) in ops.items():
            out += f"    {json.dumps(key)}: ({lit(req)}, {lit(resp)}),\n"
        out += "}\n"
        return out, ops


def generate(spec: dict, mod: str) -> tuple[str, dict, int]:
    gen = Generator(spec)
    text, ops = gen.render(mod)
    return text, ops, len(gen.defs)


def load(mod: str) -> dict:
    with gzip.open(SPECS / f"{mod}.json.gz", "rt", encoding="utf-8") as fh:
        return json.load(fh)


INIT = '"""Generated TypedDict models, one module per Bunny API (see tools/gen_types.py)."""\n'


def main(argv: list[str]) -> int:
    files = {"__init__.py": INIT}
    all_ops = {}
    for mod in MODULES:
        text, ops, count = generate(load(mod), mod)
        files[f"{mod}.py"] = text
        all_ops[mod] = {k: list(v) for k, v in ops.items()}
        print(f"{mod}: {count} types, {len(ops)} operations", file=sys.stderr)
    if "--ops" in argv:
        print(json.dumps(all_ops, indent=2))
        return 0
    if "--check" in argv:
        stale = [
            n for n, t in files.items() if not (OUT / n).exists() or (OUT / n).read_text() != t
        ]
        for n in stale:
            print(f"out of date: {OUT / n}", file=sys.stderr)
        return 1 if stale else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for n, t in files.items():
        (OUT / n).write_text(t)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
